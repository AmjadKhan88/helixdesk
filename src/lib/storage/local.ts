import { createReadStream } from "node:fs";
import { mkdir, open, stat, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { Readable } from "node:stream";
import type { StorageDriver } from "./types";

const SAFE_KEY = /^[a-zA-Z0-9-]{8,80}$/; // keys are generated by the server, never taken from users

export function createLocalDriver(): StorageDriver {
  const root = path.resolve(process.env.UPLOAD_DIR ?? ".uploads");
  const file = (key: string) => {
    if (!SAFE_KEY.test(key)) throw new Error("Invalid storage key");
    return path.join(root, key);
  };

  return {
    async put(key, body) {
      await mkdir(root, { recursive: true });
      await writeFile(file(key), body);
    },
    async head(key) {
      try {
        return { size: (await stat(file(key))).size };
      } catch {
        return null;
      }
    },
    async readHead(key, bytes) {
      try {
        const handle = await open(file(key), "r");
        try {
          const buf = Buffer.alloc(bytes);
          const { bytesRead } = await handle.read(buf, 0, bytes, 0);
          return buf.subarray(0, bytesRead);
        } finally {
          await handle.close();
        }
      } catch {
        return null;
      }
    },
    async stream(key) {
      try {
        await stat(file(key));
      } catch {
        return null;
      }
      return Readable.toWeb(
        createReadStream(file(key)),
      ) as unknown as ReadableStream;
    },
    async remove(key) {
      await unlink(file(key)).catch(() => {});
    },
  };
}
